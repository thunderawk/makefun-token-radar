// Token launch radar: comps-calibrated implied values for pre-token protocols.
//
// The value model is calibrated from the snapshot itself, not from a flat constant:
// for every category, the base multiple is the median market-cap/TVL ratio of the
// tokenized protocols in that category (winsorized, with a global median fallback).
// A pre-token protocol's implied value is its TVL times its category's multiple,
// adjusted for seven-day growth, for how long it has run with no token, and for
// how many chains it runs on. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard prints the calibration table so a
// reader can check the multiple behind any rank.
//
//   multiple(cat) = median(mcap_usd / tvl_usd) over live-token comps in cat,
//                   winsorized to [0.02, 2.5], then shrunk toward the global
//                   median: used = (n * median + 4 * global) / (n + 4), so a
//                   category with one or two comps cannot set an extreme multiple
//   growthMult    = 1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturityMult  = 0.6 + min(age_days, 1095) / 1095 * 0.4   (unknown age: 365)
//   breadthMult   = 1 + 0.02 * min(chains - 1, 5)            (at most 1.10)
//   implied       = max(1, round(tvl_usd * multiple * growthMult * maturityMult * breadthMult))
//
// The board covers every slug in the snapshot's watchlist (the floor, never the
// ceiling) plus the 260 pre-token protocols below the floor with the most TVL.
// Live-token protocols are kept apart and shown at the market's own values.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

